#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn telemetry_events_use_screaming_snake_tags() {
        let json = serde_json::json!({
            "type": "SHARD_END",
            "launch_id": Uuid::nil(),
            "shard_index": 2,
            "timestamp": "2026-11-01T10:00:00Z"
        });
        let event: TelemetryEvent = serde_json::from_value(json).unwrap();
        assert!(matches!(
            event,
            TelemetryEvent::ShardEnd {
                shard_index: 2,
                status: None,
                ..
            }
        ));
    }

    #[test]
    fn launch_init_round_trips_through_the_enum() {
        let init = LaunchInit {
            project_slug: "web".into(),
            ci_run_id: "123".into(),
            build_number: None,
            branch: Some("main".into()),
            commit_sha: None,
            shard_index: 1,
            total_shards: 2,
            shard_total_tests: 40,
            timestamp: Utc::now(),
        };
        let value = serde_json::to_value(TelemetryEvent::LaunchInit(init)).unwrap();
        assert_eq!(value["type"], "LAUNCH_INIT");
        assert_eq!(value["branch"], "main");
    }

    #[test]
    fn diffs_are_tagged_by_kind() {
        let diff = SseStateDiff::LaunchCompleted {
            launch_id: Uuid::nil(),
            status: "passed".into(),
            ended_at: Utc::now(),
        };
        let value = serde_json::to_value(diff).unwrap();
        assert_eq!(value["kind"], "LAUNCH_COMPLETED");
    }
}
