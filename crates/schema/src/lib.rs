//! KlovPlay wire contract.
//!
//! Every type here is the single source of truth for one shape on the wire.
//! `cargo test -p klovplay-schema` exports them to TypeScript with ts-rs:
//! producer-side types go to the Playwright reporter, read-side types to the
//! web dashboard.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use ts_rs::TS;
use uuid::Uuid;

// ---------------------------------------------------------------------------
// Producer → server: telemetry
// ---------------------------------------------------------------------------

/// Lifecycle events streamed by the reporter in ordered batches.
///
/// Every event is idempotent: ids are generated by the reporter, so re-sending
/// a batch after a timeout never duplicates data.
#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(
    export,
    export_to = "../../packages/playwright-reporter/src/generated/"
)]
#[serde(tag = "type", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum TelemetryEvent {
    /// Sent once per shard to `POST /api/v1/launches/init`, not in event batches.
    LaunchInit(LaunchInit),
    TestStart {
        launch_id: Uuid,
        /// One execution per attempt; a retry gets a new execution id.
        execution_id: Uuid,
        playwright_test_id: String,
        title: String,
        /// Relative to the Playwright root directory, `/`-separated.
        file_path: String,
        #[serde(default)]
        line: i32,
        suite_path: Vec<String>,
        browser_project: String,
        worker_index: i32,
        /// Stable worker slot (0..workers-1); survives worker restarts, unlike `worker_index`.
        #[serde(default)]
        parallel_index: i32,
        shard_index: i32,
        retry_attempt: i32,
        annotations: AllureAnnotations,
        timestamp: DateTime<Utc>,
    },
    StepStart {
        launch_id: Uuid,
        execution_id: Uuid,
        step_id: Uuid,
        #[ts(optional = nullable)]
        parent_step_id: Option<Uuid>,
        title: String,
        category: String,
        timestamp: DateTime<Utc>,
    },
    StepEnd {
        launch_id: Uuid,
        execution_id: Uuid,
        step_id: Uuid,
        status: String,
        duration_ms: i32,
        #[ts(optional = nullable)]
        error_message: Option<String>,
        timestamp: DateTime<Utc>,
    },
    TestEnd {
        launch_id: Uuid,
        execution_id: Uuid,
        /// passed | failed | timedOut | skipped | interrupted. Expected failures
        /// (`test.fail()`) arrive as `passed`, unexpected passes as `failed`.
        status: String,
        duration_ms: i32,
        #[ts(optional = nullable)]
        error_message: Option<String>,
        #[ts(optional = nullable)]
        error_stack: Option<String>,
        /// Playwright's source snippet around the failing line (may contain ANSI colors).
        #[serde(default)]
        #[ts(optional = nullable)]
        error_snippet: Option<String>,
        stdout: Vec<String>,
        stderr: Vec<String>,
        /// Labels as of the end of the test, including ones added at runtime
        /// (`test.info().annotations`). Replaces the TEST_START labels when present.
        #[serde(default)]
        #[ts(optional = nullable)]
        annotations: Option<AllureAnnotations>,
        timestamp: DateTime<Utc>,
    },
    ShardEnd {
        launch_id: Uuid,
        shard_index: i32,
        /// Playwright's final status for this shard: passed | failed | timedout | interrupted.
        #[serde(default)]
        #[ts(optional = nullable)]
        status: Option<String>,
        timestamp: DateTime<Utc>,
    },
}

