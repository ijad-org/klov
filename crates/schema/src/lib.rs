#[derive(Debug, Clone, Serialize, Deserialize, TS)]
#[ts(export, export_to = "../../apps/web/src/generated/")]
#[serde(tag = "kind", rename_all = "SCREAMING_SNAKE_CASE")]
pub enum SseStateDiff {
    CountersUpdated {
        launch_id: Uuid,
        total_tests: i32,
        passed: i32,
        failed: i32,
        flaky: i32,
        skipped: i32,
        running: i32,
    },
    WorkerActivity {
        /// e.g. "shard-1-worker-2" (shard index, parallel slot).
        worker_id: String,
        #[ts(optional = nullable)]
        execution_id: Option<Uuid>,
        #[ts(optional = nullable)]
        test_title: Option<String>,
        #[ts(optional = nullable)]
        current_step: Option<String>,
        /// running | idle
        status: String,
        /// When the current step (or the test, before its first step) started.
        started_at: DateTime<Utc>,
    },
    /// Carries the full row so new tests can be placed in the tree as they start.
    TestRowUpdated(Box<TestRow>),
    ArtifactUploaded {
        execution_id: Uuid,
        artifact_id: Uuid,
    },
    LaunchCompleted {
        launch_id: Uuid,
        status: String,
        ended_at: DateTime<Utc>,
    },
}

