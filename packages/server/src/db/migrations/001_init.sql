-- Klov schema v1. Requires PostgreSQL 13+ (gen_random_uuid is built in).

CREATE TABLE projects (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  slug        text NOT NULL UNIQUE,
  name        text NOT NULL,
  run_seq     integer NOT NULL DEFAULT 0,
  settings    jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE runs (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id      uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  seq             integer NOT NULL,
  name            text NOT NULL,
  run_key         text,
  status          text NOT NULL DEFAULT 'running',
  started_at      timestamptz NOT NULL DEFAULT now(),
  ended_at        timestamptz,
  duration_ms     bigint,
  last_event_at   timestamptz NOT NULL DEFAULT now(),
  reaped          boolean NOT NULL DEFAULT false,
  shard_total     integer,
  shards_finished integer[] NOT NULL DEFAULT '{}',
  shard_statuses  text[] NOT NULL DEFAULT '{}',
  stats           jsonb NOT NULL DEFAULT '{}'::jsonb,
  ci              jsonb NOT NULL DEFAULT '{}'::jsonb,
  environment     jsonb NOT NULL DEFAULT '{}'::jsonb,
  config          jsonb NOT NULL DEFAULT '{}'::jsonb,
  tags            text[] NOT NULL DEFAULT '{}',
  errors          jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, seq),
  UNIQUE (project_id, run_key)
);
CREATE INDEX runs_project_started_idx ON runs (project_id, started_at DESC);
CREATE INDEX runs_running_idx ON runs (last_event_at) WHERE status = 'running';

-- One row per test case per run. Retries are rows in "attempts".
CREATE TABLE tests (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  run_id            uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  project_id        uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  pw_test_id        text NOT NULL,
  history_key       text NOT NULL,
  title             text NOT NULL,
  title_path        text[] NOT NULL DEFAULT '{}',
  file              text NOT NULL,
  line              integer,
  col               integer,
  pw_project        text NOT NULL DEFAULT '',
  tags              text[] NOT NULL DEFAULT '{}',
  annotations       jsonb NOT NULL DEFAULT '[]'::jsonb,
  labels            jsonb NOT NULL DEFAULT '{}'::jsonb,
  status            text NOT NULL DEFAULT 'queued',
  expected_status   text,
  retries           integer NOT NULL DEFAULT 0,
  duration_ms       bigint,
  started_at        timestamptz,
  ended_at          timestamptz,
  error_message     text,
  error_fingerprint text,
  category          text,
  shard             integer,
  UNIQUE (run_id, pw_test_id)
);
CREATE INDEX tests_run_status_idx ON tests (run_id, status);
CREATE INDEX tests_run_history_idx ON tests (run_id, history_key);
CREATE INDEX tests_history_idx ON tests (project_id, history_key);
CREATE INDEX tests_run_fingerprint_idx ON tests (run_id, error_fingerprint) WHERE error_fingerprint IS NOT NULL;

CREATE TABLE attempts (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  test_id         uuid NOT NULL REFERENCES tests(id) ON DELETE CASCADE,
  run_id          uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  retry           integer NOT NULL,
  status          text NOT NULL,
  started_at      timestamptz,
  duration_ms     bigint,
  worker_index    integer,
  parallel_index  integer,
  errors          jsonb NOT NULL DEFAULT '[]'::jsonb,
  steps           jsonb NOT NULL DEFAULT '[]'::jsonb,
  stdout          text,
  stderr          text,
  annotations     jsonb NOT NULL DEFAULT '[]'::jsonb,
  UNIQUE (test_id, retry)
);
CREATE INDEX attempts_run_idx ON attempts (run_id);

-- Attachment ids are generated by the client so metadata (from test.end) and
-- the blob upload can arrive in either order.
CREATE TABLE attachments (
  id            uuid PRIMARY KEY,
  run_id        uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  test_id       uuid REFERENCES tests(id) ON DELETE CASCADE,
  retry         integer,
  name          text NOT NULL DEFAULT '',
  content_type  text NOT NULL DEFAULT 'application/octet-stream',
  size          bigint,
  storage_key   text,
  uploaded      boolean NOT NULL DEFAULT false,
  skipped       boolean NOT NULL DEFAULT false,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX attachments_test_idx ON attachments (test_id);
CREATE INDEX attachments_run_idx ON attachments (run_id);

-- Live events too large for a NOTIFY payload are parked here and referenced by id.
CREATE TABLE live_events (
  id          bigserial PRIMARY KEY,
  payload     jsonb NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
